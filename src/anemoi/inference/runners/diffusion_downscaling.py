import datetime
import logging
from collections.abc import Generator

import numpy as np
from anemoi.utils.dates import frequency_to_timedelta as to_timedelta
from anemoi.utils.timer import Timer

from anemoi.inference.config.run import RunConfiguration
from anemoi.inference.lazy import torch
from anemoi.inference.profiler import ProfilingLabel
from anemoi.inference.types import FloatArray
from anemoi.inference.types import State

from . import runner_registry
from .downscaling import DownscalingRunner

LOG = logging.getLogger(__name__)


@runner_registry.register("diffusion_downscaling")
class DiffusionDownscalingRunner(DownscalingRunner):
    """Same-time spatial diffusion downscaling runner with ensemble support.

    Designed for :class:`AnemoiD2ModelEncProcDec` checkpoints with a
    multi-dataset dict-batch interface (datasets: ``in_lres``, ``in_hres``
    → ``out_hres``).

    Inherits :meth:`forecast_stepper` from :class:`DownscalingRunner`:
    the output valid date equals the forcing date (no autoregressive rollout).

    The ensemble is generated by calling :meth:`predict_step` ``num_members``
    times per valid date.  Each call draws a fresh noise sample inside
    ``AnemoiD2ModelEncProcDec.sample``, producing an independent realisation.
    The diffusion scheduler and sampler can be overridden at inference time via
    the standard ``predict_kwargs`` block in the YAML config.

    Each yielded :class:`State` carries a ``"member"`` key (0-indexed ``int``)
    so the output handler can route members to separate files or stack them.

    Usage (YAML)::

        runner: diffusion_downscaling
        num_members: 10          # ensemble size; default 1

        # Diffusion overrides — omit to use checkpoint defaults (50 Heun steps)
        predict_kwargs:
          noise_scheduler_params:
            num_steps: 50
          sampler_params:
            S_churn: 0.0

    Extension to two-grid (Option B)
    ---------------------------------
    Override :meth:`_hres_grid_metadata` to return the high-resolution lat/lon
    arrays; the rest of the runner is grid-agnostic.
    """

    def __init__(self, config: RunConfiguration, *, num_members: int = 1) -> None:
        super().__init__(config)
        self.num_members = num_members
        LOG.info(
            "%s: %d ensemble member(s) per timestep.",
            self.__class__.__name__,
            self.num_members,
        )

    # ------------------------------------------------------------------
    # Grid metadata hook — override for two-grid (Option B) inference
    # ------------------------------------------------------------------

    def _hres_grid_metadata(self) -> tuple[np.ndarray, np.ndarray] | None:
        """Return (latitudes, longitudes) for the output grid, or ``None``.

        Same-grid (Option A, current): returns ``None`` — the base runner
        reads coordinates from the checkpoint supporting arrays.

        Two-grid (Option B, future): override this method to return the
        high-resolution lat/lon arrays so the output state carries the correct
        grid metadata for writing.

        Returns
        -------
        tuple[np.ndarray, np.ndarray] | None
            ``(latitudes, longitudes)`` in degrees, or ``None`` for same-grid.
        """
        return None

    # ------------------------------------------------------------------
    # Core inference — ensemble loop
    # ------------------------------------------------------------------

    def forecast(
        self,
        lead_time: str,
        input_tensors_numpy: dict[str, FloatArray],
        input_states: dict[str, State],
    ) -> Generator[dict[str, State], None, None]:
        """Forecast with an ensemble loop over ``num_members`` noise draws.

        For each valid date the model is called ``num_members`` times.
        Each call draws fresh Gaussian noise inside
        ``AnemoiD2ModelEncProcDec.sample``, producing an independent sample.
        States are yielded one per member, each carrying a ``"member"`` key.

        Parameters
        ----------
        lead_time : str
            Lead time string (e.g. ``"6h"``), forwarded to the stepper.
        input_tensors_numpy : dict[str, FloatArray]
            Input tensors per dataset, numpy arrays with shape
            ``(multi_step_input, variables, grid_points)``.
        input_states : dict[str, State]
            Input states per dataset, keyed by dataset name.

        Yields
        ------
        dict[str, State]
            One state dict per ensemble member per valid date.
            Each state carries ``"date"``, ``"step"``, ``"member"``, and
            ``"fields"`` (a mapping from variable name to 1-D numpy array).
        """
        with torch.inference_mode():
            self.model.eval()

            # Build torch input tensors once.
            # The base Runner converts (multi_step, vars, grid) → (1, multi_step, grid, vars).
            input_tensors_torch: dict[str, "torch.Tensor"] = {
                ds: torch.from_numpy(np.swapaxes(t, -2, -1)[np.newaxis, ...]).to(self.device)
                for ds, t in input_tensors_numpy.items()
            }

            lead_time_td = to_timedelta(lead_time)
            start = next(iter(input_states.values()))["date"]

            LOG.info("Starting diffusion downscaling from %s", start)

            if self.verbosity > 0:
                for ds, handler in self.tensor_handlers.items():
                    handler._print_input_tensor(
                        f"[{ds}] Input tensor", input_tensors_torch[ds]
                    )

            hres_grid = self._hres_grid_metadata()

            for s, (step, dates, _next_dates, is_last) in enumerate(
                self.forecast_stepper(start, lead_time_td)
            ):
                valid_date: datetime.datetime = dates[0]

                # ---- ensemble loop ----------------------------------------
                for member in range(self.num_members):
                    with (
                        torch.autocast(device_type=self.device.type, dtype=self.autocast),
                        ProfilingLabel("Predict step", self.use_profiler),
                        Timer(f"D² step {s + 1} member {member} ({valid_date})"),
                    ):
                        y_pred = self.predict_step(
                            self.model,
                            input_tensors_torch,
                            fcstep=s,
                            step=step,
                            date=valid_date,
                        )

                    new_states: dict[str, State] = {}

                    for ds, handler in self.tensor_handlers.items():
                        tensor = y_pred[ds]

                        # y_pred shape: (batch, [time], ensemble, grid, vars)
                        # Normalise to 5-D by inserting a time dim if needed.
                        if tensor.ndim == 4:
                            tensor = tensor.unsqueeze(1)

                        assert tensor.ndim == 5, (
                            f"[{ds}] Expected 5-D output tensor, got {tensor.shape}"
                        )

                        # Squeeze batch (0) and ensemble (2) → (time, grid, vars)
                        output = torch.squeeze(tensor, dim=(0, 2))

                        if self.verbosity > 0:
                            handler._print_output_tensor(
                                f"[{ds}] Member {member}", output.cpu().numpy()
                            )

                        state: State = {k: v for k, v in input_states[ds].items()}
                        state["fields"] = {
                            handler.metadata.output_tensor_index_to_variable[j]: output[0, :, j]
                            for j in range(output.shape[-1])
                        }
                        state["date"] = valid_date
                        state["step"] = step
                        state["member"] = member

                        # Two-grid (Option B): inject hres coordinates when available.
                        if hres_grid is not None:
                            state["latitudes"], state["longitudes"] = hres_grid

                        new_states[ds] = state

                    yield new_states

                # Same-time downscaling: input tensors do not change between
                # members or between timesteps — no tensor update needed here.
                # (Dynamic ERA5 inputs for the next timestep are fetched from
                # the Zarr at the start of the next execute() step.)

                if is_last:
                    break
